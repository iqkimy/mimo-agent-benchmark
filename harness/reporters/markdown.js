'use strict';

/**
 * MarkdownReporter — Generates a Markdown report from benchmark results.
 */

const fs = require('fs');
const path = require('path');

class MarkdownReporter {
  constructor(config = {}) {
    this.outputDir = config.outputDir || 'results';
  }

  render({ summary, results, manifest, runDir }) {
    const outputDir = runDir || this.outputDir;
    const lines = [];

    lines.push('# MiMo Agent Benchmark Report');
    lines.push('');
    lines.push(`**Date:** ${new Date(manifest.timestamp).toISOString()}`);
    lines.push(`**Model:** ${manifest.model}`);
    lines.push(`**Status:** ${manifest.status}`);
    lines.push(`**Composite Score:** ${summary.compositeScore.toFixed(3)}`);
    lines.push(`**Duration:** ${(manifest.duration / 1000).toFixed(1)}s`);
    lines.push('');

    lines.push('## Hypothesis Results');
    lines.push('');
    lines.push('| ID | Title | Score | Status |');
    lines.push('|----|-------|-------|--------|');

    for (const result of results) {
      const status = result.status === 'PASS' ? '✅ PASS' : '❌ FAIL';
      lines.push(`| ${result.hypothesis} | ${result.title} | ${result.score?.toFixed(3) || 'N/A'} | ${status} |`);
    }

    lines.push('');

    for (const result of results) {
      lines.push(`## ${result.hypothesis}: ${result.title}`);
      lines.push('');
      lines.push(`**Claim:** ${result.claim}`);
      lines.push(`**Score:** ${result.score?.toFixed(3) || 'N/A'}`);
      lines.push('');

      if (result.workloads && result.workloads.length > 0) {
        lines.push('### Workloads');
        lines.push('');
        for (const wl of result.workloads) {
          lines.push(`#### ${wl.id} (${wl.category})`);
          lines.push('');
          lines.push(`- **Score:** ${wl.result?.score?.toFixed(3) || 'N/A'}`);

          if (wl.metrics?.timing) {
            lines.push(`- **Latency P50:** ${wl.metrics.timing.p50LatencyMs}ms`);
            lines.push(`- **Latency P95:** ${wl.metrics.timing.p95LatencyMs}ms`);
          }

          if (wl.metrics?.tokens) {
            lines.push(`- **Total Tokens:** ${wl.metrics.tokens.total.total}`);
            lines.push(`- **Est. Cost:** $${wl.metrics.tokens.estimatedCost.total.toFixed(4)}`);
          }

          lines.push('');
        }
      }
    }

    lines.push('---');
    lines.push(`*Generated by MiMo Agent Benchmark v0.1.0*`);

    fs.writeFileSync(
      path.join(outputDir, 'report.md'),
      lines.join('\n')
    );
  }
}

module.exports = { MarkdownReporter };
